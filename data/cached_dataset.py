"""
data/cached_dataset.py
======================
Drop-in replacement dataset for training the classifier head on pre-computed
backbone features (generated by cache_backbone_features.py).

Loading the tiny .npz cache instead of running the backbone every epoch
reduces per-epoch data-loading time from ~500 s to < 1 s.
"""

from __future__ import annotations

import json
import os
from collections import Counter
from typing import List

import numpy as np
import torch
from torch.utils.data import Dataset


class CachedFeaturesDataset(Dataset):
    """
    Reads pre-computed backbone features from a .npz file and returns samples
    in the same tuple format as the normal collate_fn:

        (encoder_inputs, label, video_idx, metadata, pad_mask)

    where ``encoder_inputs`` is the pre-pooled feature vector (float32,
    shape ``(feature_dim,)``).  The ``pad_mask`` stored in the cache is kept
    for compatibility but is ignored during the FC-only forward pass.

    Also exposes ``video_names`` (numpy array indexed by video_idx), matching
    the ``ProcessedDataset`` interface used by ``train.py`` / ``test.py``.
    The companion JSON sidecar ``fold{N}_video_names.json`` is written by
    ``cache_backbone_features.py``.
    """

    def __init__(self, npz_path: str):
        if not os.path.exists(npz_path):
            raise FileNotFoundError(
                f"Cached features not found: {npz_path}\n"
                "Run cache_backbone_features.py first."
            )
        data = np.load(npz_path)
        self.features   = data['features'].astype(np.float32)   # (N, D)
        self.labels     = data['labels'].astype(np.int64)        # (N,)
        self.video_idxs = data['video_idxs'].astype(np.int64)    # (N,)
        self.metadata   = data['metadata'].astype(np.float32)    # (N, M)
        self.pad_masks  = data['pad_masks'].astype(np.float32)   # (N, T)

        # Load video_names sidecar.  The sidecar lives alongside the .npz with
        # the pattern fold{N}_video_names.json (one per fold, shared between
        # train and eval splits).  train.py accesses dataset.video_names[video_idx]
        # where video_idx is the integer video ID, so we expose a numpy array
        # indexed by those IDs.
        self.video_names = self._load_video_names(npz_path)

    @staticmethod
    def _load_video_names(npz_path: str) -> np.ndarray:
        """Load the video_names sidecar JSON, falling back to synthetic names."""
        # Derive sidecar path: swap split suffix for 'video_names.json'.
        # e.g. .../fold3_eval.npz  ->  .../fold3_video_names.json
        base = npz_path.rsplit('_train', 1)[0].rsplit('_eval', 1)[0]
        sidecar = base + '_video_names.json'
        if os.path.exists(sidecar):
            with open(sidecar) as f:
                names: List[str] = json.load(f)
            # This is the full per-clip list; video_names[clip_idx] = video_name.
            return np.array(names, dtype=object)
        # Fallback: generate placeholder names so code doesn't crash.
        # ON/OFF state detection will be wrong, but everything else works.
        # The list must be long enough to support any video_idx value used as
        # an index — video_idx values are clip indices so the max can be large.
        max_idx = int(np.load(npz_path)['video_idxs'].max())
        print(
            f"[WARNING] video_names sidecar not found: {sidecar}\n"
            "  Re-run cache_backbone_features.py to create it.\n"
            "  Using synthetic video names (ON/OFF medication state will be wrong)."
        )
        return np.array([f"video_{i}" for i in range(max_idx + 1)], dtype=object)

    def __len__(self) -> int:
        return len(self.labels)

    def __getitem__(self, idx: int):
        return {
            'encoder_inputs': self.features[idx],
            'label':          self.labels[idx],
            'video_idx':      self.video_idxs[idx],
            'metadata':       self.metadata[idx],
            'pad_mask':       self.pad_masks[idx],
        }


def cached_collate_fn(batch: list) -> tuple:
    """Mirrors data/dataloaders.py:collate_fn for cached feature batches."""
    e_inp      = torch.from_numpy(np.stack([e['encoder_inputs'] for e in batch]))
    labels     = torch.from_numpy(np.stack([e['label']          for e in batch]))
    video_idxs = torch.from_numpy(np.stack([e['video_idx']      for e in batch]))
    metadata   = torch.from_numpy(np.stack([e['metadata']       for e in batch]))
    pad_mask   = torch.from_numpy(np.stack([e['pad_mask']       for e in batch]))
    return e_inp, labels, video_idxs, metadata, pad_mask


def compute_class_weights_from_cache(dataset: CachedFeaturesDataset,
                                     num_classes: int) -> list[float]:
    """
    Balanced class weights matching learning/utils.py:compute_class_weights.
    """
    class_counts = Counter(dataset.labels.tolist())
    total        = len(dataset)
    weights      = [
        0.0 if class_counts[i] == 0
        else total / (num_classes * class_counts[i])
        for i in range(num_classes)
    ]
    total_w = sum(weights)
    return [w / total_w for w in weights]
